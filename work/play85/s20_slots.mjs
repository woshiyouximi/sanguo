import { boot, sleep, BASE } from './cdp.mjs';
const c = await boot();
const log = (k, v) => console.log('##', k, JSON.stringify(v));
const NAV = `(()=>({href:location.href,ym:(document.querySelector('#ym')||{}).innerText,gold:(document.querySelector('#gold')||{}).innerText,notice:((document.querySelector('#notice')||{}).innerText||'').replace(/\\s+/g,' '),badge:(document.querySelector('#slotBadge')||{}).innerText,btn:((document.querySelector('#btnSave')||{}).innerText||'').replace(/\\s+/g,' ')}))()`;
await c.goto(BASE + 'campaign.html'); await sleep(1200);
log('boot', await c.eval(NAV));
await c.shot('s20a_boot_slot');
const sb = await c.eval(`(()=>{const q=document.querySelector('#btnSave').getBoundingClientRect();return [Math.round(q.x+q.width/2),Math.round(q.y+q.height/2)];})()`);
await c.mouse(sb[0], sb[1]); await sleep(700);
log('slotRows', await c.eval(`(()=>[...document.querySelectorAll('#slotRows .slot')].map((r,i)=>({i:i+1,t:r.innerText.replace(/\\s+/g,' ').slice(0,130)})))()`));
await c.shot('s20b_save_sheet');
const l1 = await c.eval(`(()=>{const b=document.querySelector('#slotRows button[data-slot="0"][data-do="load"]'); const q=b.getBoundingClientRect(); return [Math.round(q.x+q.width/2),Math.round(q.y+q.height/2),b.innerText];})()`);
log('load1', l1);
await c.mouse(l1[0], l1[1]); await sleep(2400);
log('afterLoad1', await c.eval(NAV));
await c.shot('s20c_loaded_slot1');
const sb2 = await c.eval(`(()=>{const q=document.querySelector('#btnSave').getBoundingClientRect();return [Math.round(q.x+q.width/2),Math.round(q.y+q.height/2)];})()`);
await c.mouse(sb2[0], sb2[1]); await sleep(700);
const l2 = await c.eval(`(()=>{const b=document.querySelector('#slotRows button[data-slot="1"][data-do="load"]'); const q=b.getBoundingClientRect(); return [Math.round(q.x+q.width/2),Math.round(q.y+q.height/2)];})()`);
await c.mouse(l2[0], l2[1]); await sleep(2400);
log('afterLoad2', await c.eval(NAV));
await c.shot('s20d_loaded_slot2');
const errs = await c.errs(c.startErr);
console.log('ERRS', errs.length, JSON.stringify(errs.slice(-3)));
await c.save('s20_slots', { errs });
c.close();
